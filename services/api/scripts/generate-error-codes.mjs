// Reads the `ErrorCode` catalog from the OpenAPI contract and writes
// src/generated/error-codes.ts (git-ignored).
//
// TODO(#32): stopgap until `pnpm contracts:generate` produces the API types from the contract.
// When it lands, delete this script and point src/errors/error-codes.ts at the generated types.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const require = createRequire(import.meta.url);
const contractPath = require.resolve('@app/contracts/openapi/openapi.yaml');
const outFile = join(dirname(fileURLToPath(import.meta.url)), '../src/generated/error-codes.ts');

const contract = parse(readFileSync(contractPath, 'utf8'));
const schema = contract?.components?.schemas?.ErrorCode;
const codes = schema?.enum;
const catalog = schema?.['x-error-catalog'];

if (!Array.isArray(codes) || !Array.isArray(catalog)) {
  throw new Error('ErrorCode enum or x-error-catalog not found in the contract.');
}

const statusByCode = new Map(catalog.map((entry) => [entry.code, entry.http_status]));
for (const code of codes) {
  const status = statusByCode.get(code);
  if (!Number.isInteger(status)) {
    throw new Error(`Error code ${code} has no http_status in x-error-catalog.`);
  }
}

const entries = codes
  .map((code) => `  ${code}: { httpStatus: ${statusByCode.get(code)} },`)
  .join('\n');

const source = `// Generated by scripts/generate-error-codes.mjs from packages/contracts/openapi/openapi.yaml.
// Do not edit by hand.
export const ERROR_CATALOG = {
${entries}
} as const;

export type ErrorCode = keyof typeof ERROR_CATALOG;
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, source);
